def test_hook_scripts_detected_behind_interpreters(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    """`uv run script.py --flag` and `python3 script.py` both reference in-project scripts."""
    import json

    root = tmp_path / "p"
    (root / ".claude/hooks").mkdir(parents=True)
    for name in ("a.py", "b.py"):
        (root / ".claude/hooks" / name).write_text("print(1)\n", encoding="utf-8")
    settings = {
        "hooks": {
            "PreToolUse": [
                {
                    "hooks": [
                        {
                            "type": "command",
                            "command": "uv run $CLAUDE_PROJECT_DIR/.claude/hooks/a.py --notify",
                        }
                    ]
                }
            ],
            "Stop": [{"hooks": [{"type": "command", "command": "python3 .claude/hooks/b.py"}]}],
        }
    }
    (root / ".claude/settings.json").write_text(json.dumps(settings), encoding="utf-8")
    monkeypatch.setattr(Path, "home", classmethod(lambda cls: tmp_path / "home"))
    report = discover(root, Scope.PROJECT)
    scripts = sorted(f.display_path for f in report.findings if f.kind is HarnessKind.HOOK_SCRIPT)
    assert scripts == [".claude/hooks/a.py", ".claude/hooks/b.py"]
